// Differential test against the C reference packet reader.
//
// The C reference is normative. This test feeds the same fixed inputs through
// the C packet reader (testdata/c/oracle.c, built from the checkout named by
// NETCODE_C_DIR) and through this port's readPacket, and compares the two
// transcripts byte for byte. Each side prints one line per input in the form:
//
//	<n> <packet type or refused> <sequence> <length>
//
// The inputs are the committed golden packet vectors (testdata/packet_*.bin,
// generated by the C reference) plus one hostile input per checklist item 1 and
// 2: a bad prefix byte, a truncated packet, a wrong-size request, a replayed
// sequence, a request with wrong version info, and a request with a wrong
// protocol id. No sockets and no wall clock: keys, protocol id and the current
// timestamp are fixed, and time is an explicit argument to readPacket.
//
// Gate on NETCODE_C_DIR (the C source checkout; NETCODE_C_BIN_DIR is only for
// the pre-built example binaries) so the hermetic unit gate stays green when
// the checkout is absent. Run with:
//
//	NETCODE_C_DIR=<checkout> go test -count=1 -run TestCDifferential .
//
// The checkout must be mas-bandwidth/netcode holding the audit fixes, branch
// sprint/netcode-audit-fixes at or after 406e8d28.

type differentialInput struct {
	data  []byte
	group uint32 // replay group: 0 = fresh replay protection, non-zero shares one
}

// differentialInputs builds the fixed input list: the seven committed golden
// packet vectors followed by six hostile inputs, in a fixed order.
func differentialInputs(t *testing.T) []differentialInput {
	t.Helper()

	request := loadVector(t, "packet_connection_request.bin")
	keepAlive := loadVector(t, "packet_connection_keep_alive.bin")

	// item 1: bad prefix byte (low four bits = 7, an invalid packet type)
	badPrefix := append([]byte(nil), keepAlive...)
	badPrefix[0] = (badPrefix[0] & 0xF0) | 0x07

	// item 1: truncated packet (too small to be valid)
	truncated := keepAlive[:2]

	// item 1: wrong packet size (request is 1078 bytes; one short)
	wrongSize := request[:len(request)-1]

	// item 2: replayed sequence (same bytes, same replay group as the keep-alive)
	replayed := append([]byte(nil), keepAlive...)

	// item 1: wrong version info (corrupt the "NETCODE 1.02" field)
	wrongVersion := append([]byte(nil), request...)
	wrongVersion[1] = 'X'

	// item 1: wrong protocol id (corrupt the 64-bit protocol id field)
	wrongProtocol := append([]byte(nil), request...)
	wrongProtocol[14] ^= 0xFF

	return []differentialInput{
		{loadVector(t, "packet_connection_request.bin"), 0},
		{loadVector(t, "packet_connection_denied.bin"), 0},
		{loadVector(t, "packet_connection_challenge.bin"), 0},
		{loadVector(t, "packet_connection_response.bin"), 0},
		{keepAlive, 1},
		{loadVector(t, "packet_connection_payload.bin"), 0},
		{loadVector(t, "packet_connection_disconnect.bin"), 0},
		{badPrefix, 0},
		{truncated, 0},
		{wrongSize, 0},
		{replayed, 1},
		{wrongVersion, 0},
		{wrongProtocol, 0},
	}
}

// differentialTranscript runs the port's packet reader over the inputs and
// returns the resulting transcript in the same form the oracle prints.
func differentialTranscript(inputs []differentialInput) string {
	allowed := allPacketsAllowed()
	groups := make(map[uint32]*replayProtection)

	var out strings.Builder
	for i, in := range inputs {
		var replay *replayProtection
		if in.group == 0 {
			replay = &replayProtection{}
			replay.reset()
		} else {
			rp, ok := groups[in.group]
			if !ok {
				rp = &replayProtection{}
				rp.reset()
				groups[in.group] = rp
			}
			replay = rp
		}

		var sequence uint64
		p := readPacket(in.data, &sequence,
			fixturePacketKey(), fixtureProtocolID, 0, 0, fixturePrivateKey(),
			&allowed, replay)

		if p == nil {
			fmt.Fprintf(&out, "%d refused %d %d\n", i+1, sequence, len(in.data))
		} else {
			fmt.Fprintf(&out, "%d %d %d %d\n", i+1, p.packetType(), sequence, len(in.data))
		}
	}
	return out.String()
}

// writeDifferentialInputs writes the framed input file the oracle reads.
func writeDifferentialInputs(t *testing.T, path string, inputs []differentialInput) {
	t.Helper()

	var buf bytes.Buffer
	writeU32 := func(v uint32) {
		var b [4]byte
		binary.LittleEndian.PutUint32(b[:], v)
		buf.Write(b[:])
	}

	writeU32(uint32(len(inputs)))
	for _, in := range inputs {
		writeU32(uint32(len(in.data)))
		buf.Write(in.data)
		writeU32(in.group)
	}

	if err := os.WriteFile(path, buf.Bytes(), 0o600); err != nil {
		t.Fatalf("failed to write differential inputs: %v", err)
	}
}

func TestCDifferential(t *testing.T) {
	cDir := os.Getenv("NETCODE_C_DIR")
	if cDir == "" {
		t.Skip("set NETCODE_C_DIR to a C reference checkout (mas-bandwidth/netcode, branch sprint/netcode-audit-fixes at or after 406e8d28) to run the C differential test")
	}
	if _, err := os.Stat(filepath.Join(cDir, "netcode.c")); err != nil {
		t.Fatalf("NETCODE_C_DIR does not contain netcode.c: %v", err)
	}

	tmp := t.TempDir()
	oracleBin := filepath.Join(tmp, "oracle")
	oracleSrc := filepath.Join("testdata", "c", "oracle.c")
	sodiumSrc := filepath.Join(cDir, "sodium", "sodium.c")

	build := exec.Command("cc", "-O2", "-ffp-contract=off",
		"-I", cDir, "-I", filepath.Join(cDir, "sodium"),
		"-o", oracleBin, oracleSrc, sodiumSrc, "-lm")
	var buildOut bytes.Buffer
	build.Stdout = &buildOut
	build.Stderr = &buildOut
	if err := build.Run(); err != nil {
		t.Fatalf("failed to build oracle: %v\n%s", err, buildOut.String())
	}

	inputs := differentialInputs(t)
	inputFile := filepath.Join(tmp, "inputs.bin")
	writeDifferentialInputs(t, inputFile, inputs)

	oracle := exec.Command(oracleBin, inputFile)
	var oracleOut bytes.Buffer
	oracle.Stdout = &oracleOut
	oracle.Stderr = &oracleOut
	if err := oracle.Run(); err != nil {
		t.Fatalf("oracle failed: %v\n%s", err, oracleOut.String())
	}

	cTranscript := oracleOut.String()
	goTranscript := differentialTranscript(inputs)

	if cTranscript == goTranscript {
		return
	}

	cLines := strings.Split(cTranscript, "\n")
	gLines := strings.Split(goTranscript, "\n")
	n := len(cLines)
	if len(gLines) < n {
		n = len(gLines)
	}
	for i := 0; i < n; i++ {
		if cLines[i] != gLines[i] {
			t.Errorf("first differing line %d:\n  C:  %q\n  Go: %q", i+1, cLines[i], gLines[i])
			break
		}
	}
	t.Errorf("C and Go transcripts differ\n--- C ---\n%s--- Go ---\n%s", cTranscript, goTranscript)
}
